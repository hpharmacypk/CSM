-- =============================================================================
-- H-Pharmacy Customer Inbox — Phase 1: text chat
--
-- Access model
--   * Guests are Supabase *anonymous* users (role `authenticated`, JWT claim
--     is_anonymous = true). Each guest owns exactly one customer row and one
--     conversation.
--   * The admin role lives in `private.admins`, a schema that is NOT exposed
--     through the Data API. Only the project owner can add rows (SQL editor).
--   * Browsers get SELECT only (filtered by RLS). Every write goes through a
--     SECURITY DEFINER function that derives the sender and role from
--     auth.uid() / the JWT — never from browser-supplied values.
--   * The customer reference (HP-XXXXXX) is a label for the admin. No policy
--     or function uses it for authorization.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- Private schema (not exposed through PostgREST / the Data API)
-- -----------------------------------------------------------------------------
create schema if not exists private;
revoke all on schema private from public, anon, authenticated;
-- RLS policies call helper functions in this schema, so the authenticated role
-- needs USAGE. It still cannot reach anything that is not explicitly granted.
grant usage on schema private to authenticated;

create table private.admins (
  user_id    uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);
revoke all on table private.admins from public, anon, authenticated;
alter table private.admins enable row level security;
-- No policies: invisible to every API role. Managed via SQL editor only.

-- -----------------------------------------------------------------------------
-- Tables
-- -----------------------------------------------------------------------------
create table public.customers (
  id         uuid primary key default gen_random_uuid(),
  -- Nullable + ON DELETE SET NULL: if an anonymous auth user is ever removed,
  -- the conversation history stays visible to the admin.
  user_id    uuid unique references auth.users (id) on delete set null,
  public_ref text not null unique check (public_ref ~ '^HP-[A-HJ-NP-Z2-9]{6}$'),
  created_at timestamptz not null default now()
);

create table public.conversations (
  id                     uuid primary key default gen_random_uuid(),
  -- UNIQUE: exactly one conversation per guest, safe under concurrent tabs.
  customer_id            uuid not null unique references public.customers (id) on delete cascade,
  created_at             timestamptz not null default now(),
  last_message_at        timestamptz,
  last_message_preview   text,
  last_message_sender    text check (last_message_sender in ('customer', 'admin')),
  last_message_seq       bigint not null default 0,
  admin_last_read_seq    bigint not null default 0,
  customer_last_read_seq bigint not null default 0,
  admin_unread_count     integer not null default 0 check (admin_unread_count >= 0),
  customer_unread_count  integer not null default 0 check (customer_unread_count >= 0)
);

create index conversations_recent_idx
  on public.conversations (last_message_at desc nulls last, created_at desc);

create table public.messages (
  id                uuid primary key default gen_random_uuid(),
  -- Monotonic sequence used for stable ordering, paging and reconnect catch-up.
  seq               bigint generated always as identity unique,
  conversation_id   uuid not null references public.conversations (id) on delete cascade,
  sender_role       text not null check (sender_role in ('customer', 'admin')),
  sender_user_id    uuid references auth.users (id) on delete set null,
  -- 'image' / 'audio' are reserved for Phase 2; Phase 1 functions only write 'text'.
  type              text not null default 'text' check (type in ('text', 'image', 'audio')),
  body              text,
  attachment_path   text,
  -- Generated by the browser per send attempt; makes retries idempotent.
  client_message_id uuid not null,
  created_at        timestamptz not null default now(),
  constraint messages_client_message_unique unique (conversation_id, client_message_id),
  constraint messages_text_body check (
    type <> 'text' or (body is not null and char_length(btrim(body)) between 1 and 4000)
  )
);

create index messages_conversation_seq_idx on public.messages (conversation_id, seq desc);

-- -----------------------------------------------------------------------------
-- Table privileges: browsers may only SELECT, and only through RLS.
-- (Supabase grants ALL on new public tables to anon/authenticated by default.)
-- -----------------------------------------------------------------------------
revoke all on table public.customers, public.conversations, public.messages
  from public, anon, authenticated;
grant select on table public.customers, public.conversations, public.messages
  to authenticated;

alter table public.customers     enable row level security;
alter table public.conversations enable row level security;
alter table public.messages      enable row level security;

-- -----------------------------------------------------------------------------
-- Helper functions (private schema, used by RLS and the RPCs)
-- -----------------------------------------------------------------------------
create or replace function private.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select
    (select auth.uid()) is not null
    -- An anonymous session can never be the admin, even if mis-registered.
    and coalesce(((select auth.jwt()) ->> 'is_anonymous')::boolean, false) = false
    and exists (
      select 1 from private.admins a where a.user_id = (select auth.uid())
    );
$$;

create or replace function private.owns_conversation(p_conversation_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.conversations c
    join public.customers cu on cu.id = c.customer_id
    where c.id = p_conversation_id
      and cu.user_id = (select auth.uid())
  );
$$;

create or replace function private.generate_customer_ref()
returns text
language plpgsql
volatile
set search_path = ''
as $$
declare
  -- No 0/O, 1/I to avoid confusion when read aloud.
  alphabet constant text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  bytes bytea := extensions.gen_random_bytes(6);
  result text := 'HP-';
  i int;
begin
  for i in 0..5 loop
    result := result || substr(alphabet, (get_byte(bytes, i) % 32) + 1, 1);
  end loop;
  return result;
end;
$$;

revoke all on function private.is_admin()                from public, anon, authenticated;
revoke all on function private.owns_conversation(uuid)    from public, anon, authenticated;
revoke all on function private.generate_customer_ref()    from public, anon, authenticated;
-- Needed so RLS policies can evaluate them for signed-in users.
grant execute on function private.is_admin()             to authenticated;
grant execute on function private.owns_conversation(uuid) to authenticated;

-- -----------------------------------------------------------------------------
-- Row Level Security (SELECT only; there are no write policies at all)
-- -----------------------------------------------------------------------------
create policy customers_select_own_or_admin
  on public.customers for select to authenticated
  using (user_id = (select auth.uid()) or (select private.is_admin()));

create policy conversations_select_own_or_admin
  on public.conversations for select to authenticated
  using ((select private.is_admin()) or private.owns_conversation(id));

create policy messages_select_own_or_admin
  on public.messages for select to authenticated
  using ((select private.is_admin()) or private.owns_conversation(conversation_id));

-- -----------------------------------------------------------------------------
-- RPC: guest bootstrap
-- -----------------------------------------------------------------------------
create or replace function public.get_or_create_my_conversation()
returns uuid
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_uid uuid := (select auth.uid());
  v_customer_id uuid;
  v_conversation_id uuid;
  v_attempt int := 0;
begin
  if v_uid is null then
    raise exception 'Not signed in' using errcode = '42501';
  end if;
  if coalesce(((select auth.jwt()) ->> 'is_anonymous')::boolean, false) = false then
    raise exception 'Only guest sessions can open a customer inbox' using errcode = '42501';
  end if;

  select id into v_customer_id from public.customers where user_id = v_uid;

  while v_customer_id is null loop
    v_attempt := v_attempt + 1;
    begin
      insert into public.customers (user_id, public_ref)
      values (v_uid, private.generate_customer_ref())
      on conflict (user_id) do nothing
      returning id into v_customer_id;
    exception when unique_violation then
      -- public_ref collision: retry with a new reference.
      if v_attempt >= 10 then raise; end if;
    end;
    if v_customer_id is null then
      -- Another tab created it concurrently.
      select id into v_customer_id from public.customers where user_id = v_uid;
    end if;
  end loop;

  insert into public.conversations (customer_id)
  values (v_customer_id)
  on conflict (customer_id) do nothing;

  select id into v_conversation_id
  from public.conversations where customer_id = v_customer_id;

  return v_conversation_id;
end;
$$;

-- -----------------------------------------------------------------------------
-- RPC: send a text message (sender + role derived from the session)
-- -----------------------------------------------------------------------------
create or replace function public.send_message(
  p_conversation_id   uuid,
  p_body              text,
  p_client_message_id uuid
)
returns public.messages
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_uid  uuid := (select auth.uid());
  v_role text;
  v_body text := btrim(coalesce(p_body, ''));
  v_msg  public.messages;
begin
  if v_uid is null then
    raise exception 'Not signed in' using errcode = '42501';
  end if;
  if p_conversation_id is null or p_client_message_id is null then
    raise exception 'Missing conversation or message id' using errcode = '22023';
  end if;

  if private.is_admin() then
    v_role := 'admin';
  elsif private.owns_conversation(p_conversation_id) then
    v_role := 'customer';
  else
    -- Same error whether the conversation exists or not.
    raise exception 'Conversation not found' using errcode = '42501';
  end if;

  if char_length(v_body) < 1 or char_length(v_body) > 4000 then
    raise exception 'Message must be 1–4000 characters' using errcode = '22023';
  end if;

  -- Serialize sends per conversation so seq order matches commit order.
  perform 1 from public.conversations where id = p_conversation_id for update;
  if not found then
    raise exception 'Conversation not found' using errcode = '42501';
  end if;

  -- Idempotent retry: same client id returns the original row.
  select * into v_msg from public.messages
  where conversation_id = p_conversation_id
    and client_message_id = p_client_message_id;
  if found then
    if v_msg.sender_user_id is distinct from v_uid then
      raise exception 'Duplicate message id' using errcode = '23505';
    end if;
    return v_msg;
  end if;

  insert into public.messages
    (conversation_id, sender_role, sender_user_id, type, body, client_message_id)
  values
    (p_conversation_id, v_role, v_uid, 'text', v_body, p_client_message_id)
  returning * into v_msg;

  update public.conversations c set
    last_message_at       = v_msg.created_at,
    last_message_preview  = left(v_body, 140),
    last_message_sender   = v_role,
    last_message_seq      = v_msg.seq,
    admin_unread_count    = case when v_role = 'customer' then c.admin_unread_count + 1 else c.admin_unread_count end,
    customer_unread_count = case when v_role = 'admin' then c.customer_unread_count + 1 else c.customer_unread_count end,
    -- The sender has obviously read up to their own message.
    admin_last_read_seq    = case when v_role = 'admin' then v_msg.seq else c.admin_last_read_seq end,
    customer_last_read_seq = case when v_role = 'customer' then v_msg.seq else c.customer_last_read_seq end
  where c.id = p_conversation_id;

  return v_msg;
end;
$$;

-- -----------------------------------------------------------------------------
-- RPC: mark a conversation read for the caller's role
-- -----------------------------------------------------------------------------
create or replace function public.mark_conversation_read(p_conversation_id uuid)
returns void
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_uid uuid := (select auth.uid());
begin
  if v_uid is null then
    raise exception 'Not signed in' using errcode = '42501';
  end if;

  if private.is_admin() then
    update public.conversations
       set admin_unread_count = 0,
           admin_last_read_seq = last_message_seq
     where id = p_conversation_id
       and (admin_unread_count <> 0 or admin_last_read_seq <> last_message_seq);
  elsif private.owns_conversation(p_conversation_id) then
    update public.conversations
       set customer_unread_count = 0,
           customer_last_read_seq = last_message_seq
     where id = p_conversation_id
       and (customer_unread_count <> 0 or customer_last_read_seq <> last_message_seq);
  else
    raise exception 'Conversation not found' using errcode = '42501';
  end if;
end;
$$;

-- -----------------------------------------------------------------------------
-- RPC: lets the admin UI confirm membership (returns false for everyone else)
-- -----------------------------------------------------------------------------
create or replace function public.am_i_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select private.is_admin();
$$;

-- Function privileges: Supabase grants EXECUTE on new public functions to
-- anon + authenticated by default. Lock to signed-in users only.
revoke all on function public.get_or_create_my_conversation()           from public, anon, authenticated;
revoke all on function public.send_message(uuid, text, uuid)           from public, anon, authenticated;
revoke all on function public.mark_conversation_read(uuid)             from public, anon, authenticated;
revoke all on function public.am_i_admin()                             from public, anon, authenticated;
grant execute on function public.get_or_create_my_conversation()        to authenticated;
grant execute on function public.send_message(uuid, text, uuid)        to authenticated;
grant execute on function public.mark_conversation_read(uuid)          to authenticated;
grant execute on function public.am_i_admin()                          to authenticated;

